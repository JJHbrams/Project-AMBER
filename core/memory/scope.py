"""
연속성 스코프 정의.

scope_key 는 "어느 UI 채널인가"가 아니라 "어느 기억 바구니인가"를 가리킨다.
이 구분이 무너지면 코드를 읽는 쪽이 매번 overlay 창 이야기로 오해하고,
"프로젝트별로 나누는 게 깔끔하지 않나"라는 결론에 도달한다. 그 분리가
연속체를 죽인다.
"""

# 연속체의 기억이 실제로 쌓이는 단일 바구니.
#
# 말풍선·터미널 채팅·CLI 세션·원격 터널이 **모두 이 하나를 공유해야**
# 기억이 이어진다. 원격 접속에서도 같은 값을 쓰는 이유가 이것이다 —
# 접속 경로가 달라도 연속체는 하나여야 하니까.
#
# 값이 "overlay" 인 것은 역사적 이유다(overlay 가 최초 유일한 진입점이었다).
# 이름은 채널처럼 보이지만 의미는 연속성 단위다. 값을 바꾸면 여기에 묶인
# 과거 기억 전체와 끊긴다 — 2026-09-16 실측 598세션 / 35,846메시지.
# 심볼로만 부르고 값은 건드리지 않는다.
CONTINUUM_SCOPE = "overlay"

# ── 설정 레이어와의 관계 ──────────────────────────────────
#
# runtime_config 에 memory.scope.default_main("default:main") 이 있지만
# get_default_main_scope_key() 를 부르는 곳이 없다(2026-09-16 확인). 즉 설정으로
# 바꿀 수 있는 것처럼 보이지만 실제 경로는 전부 이 하드코딩 값을 탄다.
# DEFAULT_SCOPE_KEY(= default_fallback)도 bus.py 만 쓰고 overlay 경로는 안 탄다.
#
# 여기가 단일 진실이다. 설정으로 바꾸고 싶어지면 먼저 "바꾼 뒤에도 과거 기억에
# 닿는가"를 메시지 수로 재고 나서 할 것.

# 의도적으로 연속성을 끊고 싶을 때만 쓰는 접두사.
# 격리 실험, 일회성 런타임 검증처럼 "이 기록은 연속체에 섞이면 안 된다"가
# 분명할 때만. 일반 프로젝트 작업에는 쓰지 않는다 — 실측상 project:* 스코프는
# 세션만 쌓이고 메시지는 한 자릿수인 껍데기다.
ISOLATED_SCOPE_PREFIXES = ("project:", "runtime:")


def is_continuum(scope_key: str | None) -> bool:
    """연속체 본체 스코프인지 판정한다."""
    return (scope_key or "") == CONTINUUM_SCOPE
